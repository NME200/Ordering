/**
 * 订单金额与规模上限。
 *
 * 这些边界必须存在，否则实测可复现两类真实故障：
 * - **金额为负**：菜品价 0 元 + 规格增量 -1 亿分，能下出一张 -100 万元的单，
 *   再走线下收款就落出一张负数支付单；
 * - **int 溢出**：金额列是 MySQL `int`（上限 2147483647 分），
 *   999 份 × 大额规格增量会溢出并让下单直接报 500，而不是给出可读的参数错误。
 */

/** 单笔订单允许的菜品行数上限（一桌点餐的实际上限，同时限制单次请求构造的查询规模） */
export const MAX_ORDER_ITEM_LINES = 50;

/** 单行明细的最大份数 */
export const MAX_ORDER_QUANTITY_PER_LINE = 999;

/**
 * 单笔订单应付金额上限（分）＝ 100 万元。
 * 必须显著小于 MySQL `int` 上限 2147483647 分（约 2147 万元），留足余量。
 */
export const MAX_ORDER_PAYABLE_CENT = 100000000;
